CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;

DO $schedule$
DECLARE
  v_job record;
BEGIN
  FOR v_job IN
    SELECT jobid FROM cron.job WHERE jobname = 'promptgen-ops-health-scan'
  LOOP
    PERFORM cron.unschedule(v_job.jobid);
  END LOOP;

  PERFORM cron.schedule(
    'promptgen-ops-health-scan',
    '*/5 * * * *',
    $command$SELECT public.scan_ops_health();$command$
  );
END;
$schedule$;
